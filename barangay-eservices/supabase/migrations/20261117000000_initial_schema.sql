create or replace function public.create_document_request(
  p_doc_type_id bigint,
  p_purpose text,
  p_copies smallint default 1
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id uuid;
  v_fee numeric(8, 2);
begin
  if auth.uid() is null or public.current_user_role() <> 'resident' then
    raise exception 'Only active residents can create document requests';
  end if;
  if p_copies not between 1 and 5 or char_length(trim(p_purpose)) not between 1 and 255 then
    raise exception 'Invalid request details';
  end if;

  select d.fee into v_fee
  from public.document_types d
  where d.id = p_doc_type_id and not d.is_archived;
  if not found then
    raise exception 'Document type is unavailable';
  end if;

  insert into public.document_requests (resident_id, doc_type_id, purpose, copies, fee_amount)
  values (auth.uid(), p_doc_type_id, trim(p_purpose), p_copies, v_fee * p_copies)
  returning id into v_id;

  update public.document_requests
  set reference_no = 'REQ-' || to_char(now() at time zone 'Asia/Manila', 'YYMMDD') || '-' || upper(left(replace(v_id::text, '-', ''), 12))
  where id = v_id;

  insert into public.request_status_history (request_id, to_status, changed_by)
  values (v_id, 'Pending', auth.uid());
  insert into public.activity_logs (user_id, action, entity_type, entity_id)
  values (auth.uid(), 'request_created', 'document_request', v_id::text);
  return v_id;
end;
$$;

create or replace function public.transition_document_request(
  p_request_id uuid,
  p_to_status text,
  p_remarks text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_request public.document_requests%rowtype;
  v_role text := public.current_user_role();
begin
  if auth.uid() is null or v_role is null then
    raise exception 'Sign in with an active account to update requests';
  end if;

  select * into v_request from public.document_requests
  where id = p_request_id for update;
  if not found then
    raise exception 'Request not found';
  end if;

  if v_role = 'resident' then
    if v_request.resident_id <> auth.uid()
      or v_request.status <> 'Pending'
      or p_to_status <> 'Cancelled' then
      raise exception 'Residents may only cancel their own pending requests';
    end if;
  elsif v_role in ('staff', 'admin') then
    if not (
      (v_request.status = 'Pending' and p_to_status in ('Under Review', 'Cancelled'))
      or (v_request.status = 'Under Review' and p_to_status in ('Approved', 'Rejected'))
      or (v_request.status = 'Approved' and p_to_status = 'Processing')
      or (v_request.status = 'Processing' and p_to_status = 'Ready for Pickup')
      or (v_request.status = 'Ready for Pickup' and p_to_status = 'Released')
    ) then
      raise exception 'Invalid request status transition';
    end if;
  else
    raise exception 'This role cannot update requests';
  end if;

  update public.document_requests
  set status = p_to_status,
      remarks = case when p_remarks is null then remarks else left(p_remarks, 500) end,
      handled_by = case when v_role in ('staff', 'admin') then auth.uid() else handled_by end
  where id = p_request_id;

  insert into public.request_status_history (request_id, from_status, to_status, remarks, changed_by)
  values (p_request_id, v_request.status, p_to_status, left(p_remarks, 500), auth.uid());
  insert into public.activity_logs (user_id, action, entity_type, entity_id, details)
  values (auth.uid(), 'request_status_changed', 'document_request', p_request_id::text, p_to_status);
end;
$$;

