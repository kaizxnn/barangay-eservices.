create or replace function public.admin_create_document_type(
  p_name text,
  p_description text,
  p_fee numeric,
  p_processing_days smallint,
  p_requirements text[]
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_requirement text;
  v_order smallint := 0;
begin
  if not public.is_admin() then
    raise exception 'Administrator permission required';
  end if;
  if char_length(trim(p_name)) not between 1 and 100
    or p_fee < 0
    or p_processing_days not between 1 and 30 then
    raise exception 'Invalid document type details';
  end if;

  insert into public.document_types (name, description, fee, processing_days)
  values (trim(p_name), left(coalesce(p_description, ''), 500), p_fee, p_processing_days)
  returning id into v_id;

  foreach v_requirement in array coalesce(p_requirements, array[]::text[]) loop
    if char_length(trim(v_requirement)) between 1 and 200 then
      v_order := v_order + 1;
      insert into public.document_requirements (doc_type_id, requirement_text, sort_order)
      values (v_id, trim(v_requirement), v_order);
    end if;
  end loop;
  return v_id;
end;
$$;

