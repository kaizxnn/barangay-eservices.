create or replace function public.transition_concern(
  p_concern_id uuid,
  p_to_status text,
  p_note text default null,
  p_assigned_to uuid default null,
  p_resolution text default null,
  p_priority smallint default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_concern public.concerns%rowtype;
  v_role text := public.current_user_role();
  v_assignee uuid;
begin
  if auth.uid() is null or v_role is null then
    raise exception 'Sign in with an active account to update concerns';
  end if;
  select * into v_concern from public.concerns
  where id = p_concern_id for update;
  if not found then
    raise exception 'Concern not found';
  end if;

  v_assignee := coalesce(p_assigned_to, v_concern.assigned_to);
  if v_role = 'resident' then
    if v_concern.resident_id <> auth.uid()
      or not (
        (v_concern.status = 'Submitted' and p_to_status = 'Withdrawn')
        or (v_concern.status = 'Resolved' and p_to_status = 'Closed')
      ) then
      raise exception 'Residents may only withdraw their submitted concern or close a resolved concern';
    end if;
  elsif v_role in ('staff', 'admin') then
    if p_priority is not null and p_priority not between 1 and 4 then
      raise exception 'Priority must be between 1 and 4';
    end if;
    if p_assigned_to is not null and p_to_status <> 'Assigned' then
      raise exception 'Assignment can only be changed when assigning a concern';
    end if;
    if p_to_status = 'Resolved' and char_length(trim(coalesce(p_resolution, ''))) = 0 then
      raise exception 'Add a resolution note before resolving a concern';
    end if;
    if p_assigned_to is not null then
      if not exists (
        select 1 from public.profiles p
        where p.id = p_assigned_to and p.role in ('staff', 'admin') and p.is_active
      ) then
        raise exception 'Assignee must be an active staff member';
      end if;
    end if;
    if not (
      (v_concern.status = 'Submitted' and p_to_status in ('Under Review', 'Rejected'))
      or (v_concern.status = 'Under Review' and p_to_status = 'Assigned' and v_assignee is not null)
      or (v_concern.status = 'Assigned' and p_to_status = 'In Progress' and v_concern.assigned_to = auth.uid())
      or (v_concern.status = 'In Progress' and p_to_status = 'Resolved' and v_concern.assigned_to = auth.uid())
    ) then
      raise exception 'Invalid concern status transition or assignment';
    end if;
  else
    raise exception 'This role cannot update concerns';
  end if;

  update public.concerns
  set status = p_to_status,
      assigned_to = case when v_role in ('staff', 'admin') then v_assignee else assigned_to end,
      resolution = case when p_resolution is null then resolution else left(p_resolution, 1000) end,
      priority = case when v_role in ('staff', 'admin') and p_priority is not null then p_priority else priority end
  where id = p_concern_id;

  insert into public.concern_updates (concern_id, from_status, to_status, note, changed_by)
  values (p_concern_id, v_concern.status, p_to_status, left(p_note, 1000), auth.uid());
  insert into public.activity_logs (user_id, action, entity_type, entity_id, details)
  values (auth.uid(), 'concern_status_changed', 'concern', p_concern_id::text, p_to_status);
end;
$$;

