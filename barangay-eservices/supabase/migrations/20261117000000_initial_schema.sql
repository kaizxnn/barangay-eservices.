create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, role, email, first_name, last_name, email_verified_at)
  values (
    new.id,
    'resident',
    new.email,
    coalesce(nullif(left(trim(new.raw_user_meta_data ->> 'first_name'), 60), ''), 'Resident'),
    coalesce(nullif(left(trim(new.raw_user_meta_data ->> 'last_name'), 60), ''), 'Account'),
    new.email_confirmed_at
  );
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

create or replace function public.sync_auth_user_verification()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.profiles
  set email = new.email
  where id = new.id and email is distinct from new.email;
  update public.profiles
  set email_verified_at = new.email_confirmed_at
  where id = new.id;
  return new;
end;
$$;

create trigger on_auth_user_verified
after update of email, email_confirmed_at on auth.users
for each row
when (old.email is distinct from new.email or old.email_confirmed_at is distinct from new.email_confirmed_at)
execute function public.sync_auth_user_verification();

create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.role
  from public.profiles p
  join auth.users u on u.id = p.id
  where p.id = (select auth.uid()) and p.is_active and u.email_confirmed_at is not null
$$;

