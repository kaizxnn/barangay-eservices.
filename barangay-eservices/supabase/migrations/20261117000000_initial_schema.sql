-- Supabase schema for Barangay E-Services.
-- Apply with `supabase db push` or paste into the Supabase SQL editor.

create extension if not exists pgcrypto with schema extensions;

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'resident' check (role in ('admin', 'staff', 'resident')),
  email text unique,
  first_name text not null check (char_length(first_name) between 1 and 60),
  last_name text not null check (char_length(last_name) between 1 and 60),
  contact_no text check (contact_no is null or char_length(contact_no) <= 13),
  street_address text check (street_address is null or char_length(street_address) <= 150),
  purok_id bigint,
  email_verified_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.puroks (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 60),
  created_at timestamptz not null default now()
);

alter table public.profiles
  add constraint profiles_purok_id_fkey
  foreign key (purok_id) references public.puroks (id) on delete set null;

create table public.barangay_settings (
  id boolean primary key default true check (id),
  barangay_name text,
  municipality text,
  province text,
  office_hours text,
  logo_path text,
  updated_by uuid references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now()
);

insert into public.barangay_settings (id, office_hours)
values (true, 'Monday to Friday, 8:00 AM to 5:00 PM')
on conflict (id) do nothing;

create table public.document_types (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 100),
  description text not null default '',
  fee numeric(8, 2) not null default 0 check (fee >= 0),
  processing_days smallint not null default 1 check (processing_days between 1 and 30),
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.document_requirements (
  id bigint generated by default as identity primary key,
  doc_type_id bigint not null references public.document_types (id) on delete cascade,
  requirement_text text not null check (char_length(requirement_text) between 1 and 200),
  sort_order smallint not null default 1 check (sort_order >= 0)
);

create table public.document_requests (
  id uuid primary key default gen_random_uuid(),
  reference_no text unique,
  resident_id uuid not null references public.profiles (id),
  doc_type_id bigint not null references public.document_types (id),
  purpose text not null check (char_length(purpose) between 1 and 255),
  copies smallint not null default 1 check (copies between 1 and 5),
  fee_amount numeric(8, 2) not null check (fee_amount >= 0),
  status text not null default 'Pending' check (status in (
    'Pending', 'Under Review', 'Approved', 'Rejected', 'Processing',
    'Ready for Pickup', 'Released', 'Cancelled'
  )),
  remarks text check (remarks is null or char_length(remarks) <= 500),
  handled_by uuid references public.profiles (id) on delete set null,
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index document_requests_status_idx on public.document_requests (status);
create index document_requests_created_at_idx on public.document_requests (created_at desc);
create index document_requests_resident_idx on public.document_requests (resident_id, created_at desc);

create table public.request_status_history (
  id bigint generated by default as identity primary key,
  request_id uuid not null references public.document_requests (id) on delete cascade,
  from_status text,
  to_status text not null,
  remarks text check (remarks is null or char_length(remarks) <= 500),
  changed_by uuid not null references public.profiles (id),
  changed_at timestamptz not null default now()
);

create table public.concern_categories (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 100),
  description text not null default '',
  default_priority smallint not null default 2 check (default_priority between 1 and 4),
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.concerns (
  id uuid primary key default gen_random_uuid(),
  reference_no text unique,
  resident_id uuid not null references public.profiles (id),
  category_id bigint not null references public.concern_categories (id),
  purok_id bigint not null references public.puroks (id),
  title text not null check (char_length(title) between 1 and 120),
  description text not null check (char_length(description) between 1 and 10000),
  location text not null check (char_length(location) between 1 and 200),
  priority smallint not null default 2 check (priority between 1 and 4),
  status text not null default 'Submitted' check (status in (
    'Submitted', 'Under Review', 'Assigned', 'In Progress',
    'Resolved', 'Closed', 'Rejected', 'Withdrawn'
  )),
  assigned_to uuid references public.profiles (id) on delete set null,
  resolution text check (resolution is null or char_length(resolution) <= 1000),
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index concerns_status_idx on public.concerns (status);
create index concerns_created_at_idx on public.concerns (created_at desc);
create index concerns_resident_idx on public.concerns (resident_id, created_at desc);
create index concerns_queue_idx on public.concerns (priority desc, created_at)
  where assigned_to is null and is_archived = false;

create table public.concern_updates (
  id bigint generated by default as identity primary key,
  concern_id uuid not null references public.concerns (id) on delete cascade,
  from_status text,
  to_status text not null,
  note text check (note is null or char_length(note) <= 1000),
  changed_by uuid not null references public.profiles (id),
  changed_at timestamptz not null default now()
);

create table public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles (id) on delete set null,
  action text not null check (char_length(action) between 1 and 60),
  entity_type text check (entity_type is null or char_length(entity_type) <= 40),
  entity_id text,
  details text check (details is null or char_length(details) <= 500),
  created_at timestamptz not null default now()
);

