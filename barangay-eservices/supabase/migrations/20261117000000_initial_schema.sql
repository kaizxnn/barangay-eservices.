create or replace function public.archive_document_request(p_request_id uuid, p_archived boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_request public.document_requests%rowtype;
  v_role text := public.current_user_role();
begin
  if auth.uid() is null or v_role not in ('staff', 'admin') then
    raise exception 'Staff permission required';
  end if;
  select * into v_request from public.document_requests where id = p_request_id for update;
  if not found then
    raise exception 'Request not found';
  end if;
  if p_archived and v_request.status not in ('Released', 'Rejected', 'Cancelled') then
    raise exception 'Only finished requests can be archived';
  end if;
  if not p_archived and v_role <> 'admin' then
    raise exception 'Only administrators can restore archived requests';
  end if;
  update public.document_requests set is_archived = p_archived where id = p_request_id;
  insert into public.activity_logs (user_id, action, entity_type, entity_id)
  values (auth.uid(), case when p_archived then 'request_archived' else 'request_restored' end, 'document_request', p_request_id::text);
end;
$$;

create or replace function public.archive_concern(p_concern_id uuid, p_archived boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_concern public.concerns%rowtype;
  v_role text := public.current_user_role();
begin
  if auth.uid() is null or v_role not in ('staff', 'admin') then
    raise exception 'Staff permission required';
  end if;
  select * into v_concern from public.concerns where id = p_concern_id for update;
  if not found then
    raise exception 'Concern not found';
  end if;
  if p_archived and v_concern.status not in ('Closed', 'Rejected', 'Withdrawn') then
    raise exception 'Only finished concerns can be archived';
  end if;
  if not p_archived and v_role <> 'admin' then
    raise exception 'Only administrators can restore archived concerns';
  end if;
  update public.concerns set is_archived = p_archived where id = p_concern_id;
  insert into public.activity_logs (user_id, action, entity_type, entity_id)
  values (auth.uid(), case when p_archived then 'concern_archived' else 'concern_restored' end, 'concern', p_concern_id::text);
end;
$$;

